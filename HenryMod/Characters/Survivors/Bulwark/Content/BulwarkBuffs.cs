using RoR2;
using UnityEngine;

namespace SpaceMarines.Survivors.Bulwark
{
    public static class BulwarkBuffs
    {
        // armor buff gained during roll
        public static BuffDef armorBuff;

        public static void Init(AssetBundle assetBundle)
